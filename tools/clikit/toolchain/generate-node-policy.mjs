import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseNodeEnginePolicy } from '../../../core/plugin-runtime/src/platform-resolve/node-engine.mjs';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootArgument = process.argv.indexOf('--root');
const root = path.resolve(rootArgument === -1 ? path.join(scriptDirectory, '../../..') : process.argv[rootArgument + 1]);
const check = process.argv.includes('--check');
const manifestPath = path.join(root, 'package.json');
const outputPath = path.join(root, 'tools/clikit/toolchain/node_policy_gen.go');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
const { requiredMajor } = parseNodeEnginePolicy(manifest.engines?.node);
const [packageManagerName, pnpmVersion] = String(manifest.packageManager ?? '').split('@');
if (packageManagerName !== 'pnpm' || !pnpmVersion) throw new Error('package.json must pin pnpm as packageManager');
const pnpmMajor = Number(pnpmVersion.split('.')[0]);
const generated = `// Code generated by tools/clikit/toolchain/generate-node-policy.mjs from package.json; DO NOT EDIT.\n\npackage toolchain\n\nconst (\n\tSupportedNodeMajor = ${requiredMajor}\n\tSupportedPnpmMajor = ${pnpmMajor}\n\tSupportedPnpm = "${pnpmVersion}"\n)\n`;

if (check) {
  let current;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    process.stderr.write(`generated Go Node policy is missing: ${outputPath}; run go generate ./toolchain\n`);
    process.exitCode = 1;
  }
  if (current !== undefined && current !== generated) {
    process.stderr.write(`generated Go Node policy is stale for ${manifest.engines.node}; run go generate ./toolchain\n`);
    process.exitCode = 1;
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated, 'utf8');
}

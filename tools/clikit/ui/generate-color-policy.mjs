#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { colorPolicy } from '../../../core/plugin-contracts/src/color-policy.mjs';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootOption = process.argv.indexOf('--root');
const root = path.resolve(rootOption === -1 ? path.join(scriptDirectory, '../../..') : process.argv[rootOption + 1]);
const check = process.argv.includes('--check');
const installers = [
  'tools/kb-create/install.sh',
  'tools/kb-dev/install.sh',
  'tools/kb-deploy/install.sh',
  'tools/kb-devkit/install.sh',
  'tools/kb-monitor/install.sh',
];
const outputs = [
  ['tools/clikit/ui/color_policy_gen.go', renderGo('ui')],
  ['templates/go-binary/cmd/color_policy_gen.go', renderGo('cmd')],
  ['tools/kb-dev/cmd/color_policy_cases_test.go', renderGoCases('cmd')],
];
const startMarker = '# BEGIN GENERATED COLOR POLICY';
const endMarker = '# END GENERATED COLOR POLICY';
let failed = false;

for (const [relativePath, expected] of outputs) {
  const target = path.join(root, relativePath);
  awaitGenerated(target, expected);
}
for (const relativePath of installers) {
  const target = path.join(root, relativePath);
  let source;
  try {
    source = readFileSync(target, 'utf8');
  } catch (error) {
    fail(`${relativePath} is missing: ${error.message}`);
    continue;
  }
  const expected = replaceGeneratedBlock(source, `${startMarker}\n${renderShell()}\n${endMarker}`);
  if (expected === undefined) {
    fail(`${relativePath} must contain exactly one generated color policy marker pair.`);
  } else {
    awaitGenerated(target, expected);
  }
}
if (failed) process.exitCode = 1;

function fail(message) {
  process.stderr.write(`${message}; run node tools/clikit/ui/generate-color-policy.mjs\n`);
  failed = true;
}

function awaitGenerated(target, expected) {
  let current;
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    current = undefined;
  }
  if (current !== undefined && current === expected) return;
  if (check) {
    fail(`${path.relative(root, target)} is stale`);
    return;
  }
  writeFileSync(target, expected, 'utf8');
}

function replaceGeneratedBlock(source, block) {
  const lines = source.split(/\r?\n/);
  const starts = lines.flatMap((line, index) => line === startMarker ? [index] : []);
  const ends = lines.flatMap((line, index) => line === endMarker ? [index] : []);
  if (starts.length !== 1 || ends.length !== 1 || starts[0] >= ends[0]) return undefined;
  lines.splice(starts[0], ends[0] - starts[0] + 1, ...block.split('\n'));
  return lines.join('\n');
}

function renderGo(packageName) {
  const body = colorPolicy.rules.map((rule) => {
    const condition = {
      noColorNonEmpty: 'noColor != ""',
      forceColorDisabled: 'forceColor == "0"',
      forceColorEnabled: 'forceColor != ""',
      termDumb: 'strings.EqualFold(term, "dumb")',
      tty: 'isTTY',
    }[rule.when];
    if (!condition) throw new Error(`Unsupported color rule: ${rule.when}`);
    return `\tif ${condition} {\n\t\treturn ${rule.result}\n\t}`;
  }).join('\n');
  const templateRenderer = packageName === 'cmd' ? `\nfunc configureColor(enabled bool) {\n\tif enabled {\n\t\tlipgloss.SetColorProfile(termenv.ANSI)\n\t\treturn\n\t}\n\tlipgloss.SetColorProfile(termenv.Ascii)\n}\n` : '';
  const imports = packageName === 'cmd'
    ? 'import (\n\t"github.com/charmbracelet/lipgloss"\n\t"github.com/muesli/termenv"\n\t"strings"\n)'
    : 'import "strings"';
  return `// Code generated by tools/clikit/ui/generate-color-policy.mjs from core/plugin-contracts/src/color-policy.mjs; DO NOT EDIT.\n\npackage ${packageName}\n\n${imports}\n\nfunc resolveColorSupport(isTTY bool, noColor, forceColor, term string) bool {\n${body}\n\treturn false\n}\n${templateRenderer}`;
}

function renderGoCases(packageName) {
  const cases = colorPolicy.cases.map((item) => `\t{${quoteGo(item.name)}, ${item.tty}, ${quoteGo(item.noColor)}, ${quoteGo(item.forceColor)}, ${quoteGo(item.term)}, ${item.want}},`).join('\n');
  return `// Code generated by tools/clikit/ui/generate-color-policy.mjs from core/plugin-contracts/src/color-policy.mjs; DO NOT EDIT.\n\npackage ${packageName}\n\nvar generatedColorPolicyCases = []struct {\n\tname       string\n\ttty        bool\n\tnoColor    string\n\tforceColor string\n\tterm       string\n\twant       bool\n}{\n${cases}\n}\n`;
}

function quoteGo(value) {
  return JSON.stringify(value);
}

function renderShell() {
  const body = colorPolicy.rules.map((rule) => {
    const result = rule.result ? 0 : 1;
    if (rule.when === 'termDumb') {
      return `  case "${'${TERM:-}'}" in [Dd][Uu][Mm][Bb]) return ${result} ;; esac`;
    }
    const condition = {
      noColorNonEmpty: '[ -n "${NO_COLOR:-}" ]',
      forceColorDisabled: '[ "${FORCE_COLOR:-}" = "0" ]',
      forceColorEnabled: '[ -n "${FORCE_COLOR:-}" ]',
      tty: '[ -t 1 ]',
    }[rule.when];
    if (!condition) throw new Error(`Unsupported color rule: ${rule.when}`);
    return `  if ${condition}; then return ${result}; fi`;
  }).join('\n');
  return `kb_color_enabled() {\n${body}\n  return 1\n}`;
}
